  JOIN asset_cash_events e ON e.asset_id = a.id
   AND e.type IS NOT DISTINCT FROM p.tipo
   AND e.data_com = p.data_com
   AND e.value_per_share = p.valor
   AND e.seq = p.seq
   AND e.source = p.fonte
   AND e.source_ref IS NOT DISTINCT FROM p.ref;

DELETE FROM dividends d
 USING eventos_indevidos x
 WHERE d.cash_event_id = x.id AND d.origin = 'AUTO';

UPDATE dividends d SET cash_event_id = NULL
  FROM eventos_indevidos x
 WHERE d.cash_event_id = x.id;

DELETE FROM asset_cash_events e
 USING eventos_indevidos x
 WHERE e.id = x.id;