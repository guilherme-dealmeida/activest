-- Classifica os fundos imobiliários por segmento.
--
-- Fonte: consulta de fundos imobiliários do StatusInvest, campo "segment".
-- Não há como derivar isso do que já estava no banco: a V19 carregou os 338
-- FIIs com name igual ao ticker (337 dos 338) e sector inútil — 206 nulos e o
-- restante 'Miscellaneous'. Zero sinal aproveitável, ao contrário das ações,
-- onde o setor FactSet resolvia dois terços sozinho.
--
-- Tradução do vocabulário do StatusInvest para as categorias da V15:
--   Papéis                            -> TITULOS_E_VALORES_MOBILIARIOS
--   Fundo de Fundos                   -> FUNDO_DE_FUNDOS
--   Fundo de Desenvolvimento          -> DESENVOLVIMENTO
--   Incorporações                     -> DESENVOLVIMENTO
--   Misto                             -> HIBRIDO
--   Imóveis Industriais e Logísticos  -> LOGISTICA
--   Logística                         -> LOGISTICA
--   Imóveis Residenciais              -> RESIDENCIAL
--   Lajes Corporativas / Shoppings / Agências de Bancos / Educacional /
--   Hospitalar / Hotéis               -> categoria de mesmo nome
--   Imóveis Comerciais - Outros       -> IMOVEIS_COMERCIAIS   (categoria nova)
--   Varejo                            -> VAREJO               (categoria nova)
--   Indefinido                        -> OUTROS
--   Exploração de Imóveis, Holdings Diversificadas, Serviços Financeiros
--   Diversos, Tecidos/Vestuário       -> OUTROS
--
-- "Indefinido" vira OUTROS porque a própria fonte não classifica esses fundos —
-- inventar um segmento aqui seria pior do que admitir que não se sabe.
--
-- Treze fundos não aparecem na consulta do StatusInvest (encerrados,
-- incorporados ou nunca listados) e também entram como OUTROS, por decisão
-- explícita, para não sobrar ativo sem categoria:
--   MIDW11, GSRF11, VGRH11, SPG211, TRPL15, VVDI11, PLTB11, STYI11, RTEL16,
--   JPRD11, HJCT11, NMKS11, EBTA11
--
-- Fica de fora apenas o INHF11, que não é fundo imobiliário: a V19 o trouxe com
-- nome "INTER HOLDING FINANCEIRA S.A.". A V28 o move para o tipo ACAO.
--
-- Distribuição resultante:
--   TITULOS_E_VALORES_MOBILIARIOS     68
--   OUTROS                            59
--   LAJES_CORPORATIVAS                48
--   LOGISTICA                         33
--   HIBRIDO                           33
--   SHOPPINGS                         27
--   DESENVOLVIMENTO                   22
--   FUNDO_DE_FUNDOS                   18
--   IMOVEIS_COMERCIAIS                 6
--   RESIDENCIAL                        6
--   HOSPITALAR                         5
--   AGENCIAS_BANCARIAS                 4
--   VAREJO                             3
--   HOTEL                              3
--   EDUCACIONAL                        2
--                                    ---
--                                    337
--
-- Duas categorias que a V15 não previu. O StatusInvest separa imóvel comercial
-- que não é laje corporativa, e imóvel de varejo, de quem a V15 só tinha
-- 'Shoppings'. Jogá-los em OUTROS misturaria fundos de tijolo bem definidos com
-- o balaio dos não classificados.
INSERT INTO asset_categories (asset_type_id, name, description)
SELECT t.id, c.name, c.description
FROM asset_types t
CROSS JOIN (VALUES
    ('IMOVEIS_COMERCIAIS'::varchar, 'Imóveis Comerciais'::varchar),
    ('VAREJO',                      'Varejo')
) AS c(name, description)
WHERE t.name = 'FII'
ON CONFLICT (asset_type_id, name) DO UPDATE
    SET description = EXCLUDED.description;

