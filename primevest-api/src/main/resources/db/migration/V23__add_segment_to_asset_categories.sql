-- Categoria ganha segment: a classificação passa a ter dois níveis.
--
--   FII   name/description = tipo de fundo (TIJOLO, PAPEL, FOF, HIBRIDO, OUTROS)
--         segment          = segmento de atuação (o que antes era a description)
--         Fonte: CATEGORIA_FIIS.xlsx, informada pelo usuário (337 fundos).
--
--   ACAO  name/description = setor econômico da B3
--         segment          = segmento da B3
--         Fonte: Classificação Setorial oficial da B3 (ClassifSetorial.xlsx,
--         baixada de sistemaswebb3-listados.b3.com.br em 16/09/2026). A B3
--         classifica por emissor, então todas as classes e o fracionário de um
--         mesmo emissor (4 primeiras letras do ticker) recebem a mesma linha.
--         O setor foi realinhado à B3 junto com o segmento: 136 ações estavam
--         num setor diferente do oficial (construtoras em Financeiro, Bradespar
--         em Financeiro etc.), e manter o setor antigo produziria pares
--         incoerentes como Financeiro › Incorporações. LOGG3, que estava em
--         IMOBILIARIO, vai para Financeiro › Exploração de Imóveis, como na B3.
--         FSPE11F, FSRF11F, FSTU11F e INHF11 não constam da B3 e vão para
--         OUTROS › Outros, por decisão do usuário.
--
--   Demais tipos: segment nulo.
--
-- Uma categoria agora é o par (name, segment) dentro do tipo, por isso a
-- unicidade passa a incluir segment. NULLS NOT DISTINCT (PostgreSQL 15+)
-- mantém a regra antiga para os tipos sem segmento: dois 'CDB' com segment
-- nulo continuam proibidos.
--
-- Ativos são repontados por ticker; categorias de FII e ação que ficam sem
-- nenhum ativo (as antigas, com segment nulo) são removidas no fim, com guarda.

ALTER TABLE asset_categories ADD COLUMN segment VARCHAR(255);

ALTER TABLE asset_categories DROP CONSTRAINT uk_asset_categories_scope;
ALTER TABLE asset_categories
    ADD CONSTRAINT uk_asset_categories_scope UNIQUE NULLS NOT DISTINCT (asset_type_id, name, segment);

