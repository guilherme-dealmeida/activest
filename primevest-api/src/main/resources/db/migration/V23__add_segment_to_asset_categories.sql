DO $$
DECLARE
    sem_segmento INTEGER;
BEGIN
    SELECT COUNT(*) INTO sem_segmento
    FROM assets a
    JOIN asset_types t           ON t.id = a.asset_type_id
    LEFT JOIN asset_categories c ON c.id = a.asset_category_id
    WHERE t.name IN ('FII', 'ACAO')
      AND c.segment IS NULL;

    IF sem_segmento > 0 THEN
        RAISE EXCEPTION 'V23: % ativo(s) FII/ACAO ficaram sem segment; categorias antigas não serão removidas', sem_segmento;
    END IF;
END $$;

