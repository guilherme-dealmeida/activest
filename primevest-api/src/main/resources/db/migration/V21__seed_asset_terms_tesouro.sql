-- contratado por ele.
--
-- A taxa não está aqui de propósito. No Tesouro ela é do dia da compra: dois
-- investidores levam o mesmo papel a IPCA + 6,2% e IPCA + 5,8% conforme
-- quando compraram. Taxa é da nota.
