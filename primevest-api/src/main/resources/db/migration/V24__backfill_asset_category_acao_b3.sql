-- Classifica as 242 ações cujo setor de origem (FactSet, via BrAPI) não tinha
-- destino único na taxonomia da B3 e ficaram fora da V23.
--
-- A classificação foi informada pelo usuário a partir da consulta oficial da
-- B3, ticker a ticker. Não é derivada de assets.sector: para estes papéis um
-- mesmo setor de origem se parte em setores B3 diferentes, e só a fonte oficial
-- resolve. Exemplos do que estava junto e aqui se separa:
--
--   Retail Trade           AMER3 -> Consumo Cíclico | ASAI3 -> Consumo não Cíclico | RADL3 -> Saúde
--   Consumer Non-Durables  ABEV3 -> Consumo não Cíclico | ALPA3 -> Consumo Cíclico
--   Industrial Services    AZEV3 -> Bens Industriais | MELK3 -> Consumo Cíclico | TAEE3 -> Utilidade Pública
--
-- Os papéis do mercado fracionário (sufixo F) recebem a categoria do seu par —
-- é a mesma empresa. Onde o usuário informou outra classe do mesmo emissor
-- (CEDO4 para o CEDO3F, por exemplo), a categoria foi resolvida pelo nome da
-- empresa, que é como a B3 classifica: por emissor, não por código.
--
-- Distribuição resultante:
--   CONSUMO_CICLICO                   76
--   CONSUMO_NAO_CICLICO               50
--   BENS_INDUSTRIAIS                  37
--   MATERIAIS_BASICOS                 31
--   TECNOLOGIA_DA_INFORMACAO          18
--   SAUDE                             14
--   PETROLEO_GAS_BIOCOMBUSTIVEIS       8
--   UTILIDADE_PUBLICA                  6
--   IMOBILIARIO                        2
--
-- IMOBILIARIO não existia entre as 11 categorias criadas pela V16 e é
-- acrescentado aqui: a B3 classifica a LOG Commercial Properties nesse setor, e
-- registrá-la como Financeiro seria distorcer a fonte para caber na tabela.
INSERT INTO asset_categories (asset_type_id, name, description)
SELECT t.id, 'IMOBILIARIO', 'Imobiliário'
FROM asset_types t
WHERE t.name = 'ACAO'
ON CONFLICT (asset_type_id, name) DO UPDATE
    SET description = EXCLUDED.description;

